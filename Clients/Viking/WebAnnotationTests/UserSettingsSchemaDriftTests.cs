using System.Xml.Schema;
using Microsoft.VisualStudio.TestTools.UnitTesting;
using rogue1.codepharm.net.XSD.WebAnnotationUserSettings.xsd;
using WebAnnotation;

namespace WebAnnotationTests
{
    /// <summary>
    /// Keeps three copies of the shortcut-file format in step: the schema (<c>WebAnnotationUserSettings.xsd</c>), the
    /// LinqToXsd class generated from it (<c>webannotationusersettings.cs</c>), and the shipped default file
    /// (<c>UserSettings.xml</c>). The generated class is only regenerated by hand, so an element or attribute added
    /// to the schema (or to a file users edit) that the class lacks is silently dropped when the file is loaded.
    /// A failure here is drift to report as a proposal: regenerate the class from the schema, do not edit the
    /// generated file or loosen the schema to make a test pass.
    /// </summary>
    [TestClass]
    public class UserSettingsSchemaDriftTests
    {
        private const string SchemaNamespace = "http://rogue1.codepharm.net/XSD/WebAnnotationUserSettings.xsd";
        private const string GeneratedNamespace = "rogue1.codepharm.net.XSD.WebAnnotationUserSettings.xsd";
        private const string WebAnnotationFolder = @"Clients\Viking\WebAnnotation\";

        /// <summary>
        /// Generated properties whose name differs from the schema name, as <c>"Class.schemaName"</c> to property
        /// name. LinqToXsd renames a member that would equal its own class name (<c>Value.Value</c> is
        /// <c>Value.Value1</c>) because C# forbids it.
        /// </summary>
        private static readonly Dictionary<string, string> RenamedGeneratedMembers = new()
        {
            ["Value.Value"] = "Value1",
        };

        /// <summary>
        /// Public properties that are hand-written in <c>WebAnnotationUserSettingsExt.cs</c> (the other half of the
        /// partial classes) and so have no schema counterpart, as <c>"Class.Property"</c>.
        /// </summary>
        private static readonly HashSet<string> HandWrittenMembers = new()
        {
            "Hotkey.KeyCode",
            "Parameters.Count",
            "CreateStructureCommandAction.AttributeList",
        };

        /// <summary>
        /// For each schema simple type that restricts a string to an enumeration, the production code that consumes
        /// the value. The generated class types such an attribute as plain <c>string</c>, so there is no member to
        /// check; what can drift is the consumer, whose <c>switch</c> falls back to a default for a value it does not
        /// know. A new enumeration type with no entry here fails <see cref="FindDrift"/> until someone adds one.
        /// </summary>
        private static readonly Dictionary<string, Func<string, object>> EnumerationConsumers = new()
        {
            ["AnnotationType"] = value => new CreateStructureCommandAction { AnnotationType = value }.GetLocationType(),
        };

        /// <summary>
        /// Enumeration values that legitimately produce the consumer's fallback result, as
        /// <c>"SimpleType.value"</c>. <c>Circle</c> is the fallback of <c>StringToLocationType</c>.
        /// </summary>
        private static readonly HashSet<string> EnumerationValuesEqualToFallback = new()
        {
            "AnnotationType.Circle",
        };

        private static string FindWebAnnotationFile(string fileName, [CallerFilePath] string thisSourceFile = "")
        {
            string besideSource = Path.Combine(Path.GetDirectoryName(thisSourceFile) ?? "", @"..\WebAnnotation", fileName);
            if (File.Exists(besideSource))
                return Path.GetFullPath(besideSource);

            for (DirectoryInfo? dir = new(AppDomain.CurrentDomain.BaseDirectory); dir != null; dir = dir.Parent)
            {
                string candidate = Path.Combine(dir.FullName, WebAnnotationFolder + fileName);
                if (File.Exists(candidate))
                    return candidate;
            }

            Assert.Fail($"{WebAnnotationFolder}{fileName} not found beside {thisSourceFile} or above {AppDomain.CurrentDomain.BaseDirectory}");
            return "";
        }

        private static string ReadShippedSchemaText() => File.ReadAllText(FindWebAnnotationFile("WebAnnotationUserSettings.xsd"));

        private static XmlSchemaSet CompileSchema(string schemaText)
        {
            XmlSchemaSet set = new();
            using (StringReader reader = new(schemaText))
            {
                set.Add(XmlSchema.Read(reader, null));
            }

            set.Compile();
            return set;
        }

        /// <summary>
        /// Everything the schema declares that the generated class or its consumers do not match, one line each.
        /// Empty when they agree.
        /// </summary>
        private static List<string> FindDrift(XmlSchemaSet schemas)
        {
            List<string> drift = new();
            foreach (XmlSchemaElement element in schemas.GlobalElements.Values.Cast<XmlSchemaElement>())
            {
                string name = element.QualifiedName.Name;
                Type? generated = typeof(UserSettings).Assembly.GetType($"{GeneratedNamespace}.{name}");
                if (generated == null)
                {
                    drift.Add($"element <{name}> has no generated class");
                    continue;
                }

                if (element.ElementSchemaType is XmlSchemaComplexType complex)
                    CheckComplexType(generated, complex, name, drift);
            }

            foreach (XmlSchemaSimpleType simple in schemas.GlobalTypes.Values.OfType<XmlSchemaSimpleType>())
                CheckEnumeration(simple, drift);

            return drift;
        }

        private static void CheckComplexType(Type generated, XmlSchemaComplexType complex, string path, List<string> drift)
        {
            HashSet<string> expected = new();
            foreach (XmlSchemaAttribute attribute in complex.AttributeUses.Values.Cast<XmlSchemaAttribute>())
            {
                string name = attribute.QualifiedName.Name;
                PropertyInfo? property = FindMember(generated, name, expected);
                if (property == null)
                    drift.Add($"{path}/@{name} has no property on {generated.Name}");
                else if (!AttributeBindsToName(generated, property, name))
                    drift.Add($"{path}/@{name}: {generated.Name}.{property.Name} does not read and write attribute '{name}'");
            }

            foreach (XmlSchemaElement child in ChildElements(complex.ContentTypeParticle))
            {
                string name = child.QualifiedName.Name;
                PropertyInfo? property = FindMember(generated, name, expected);
                if (property == null)
                {
                    drift.Add($"{path}/{name} has no property on {generated.Name}");
                    continue;
                }

                bool isReferenceToGlobalElement = !child.RefName.IsEmpty;
                if (isReferenceToGlobalElement || child.ElementSchemaType is not XmlSchemaComplexType childType)
                    continue;

                Type? nested = generated.GetNestedType(name + "LocalType");
                if (nested == null)
                    drift.Add($"{path}/{name} has no nested class {generated.Name}.{name}LocalType");
                else
                    CheckComplexType(nested, childType, $"{path}/{name}", drift);
            }

            foreach (PropertyInfo extra in generated.GetProperties(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly))
            {
                if (!expected.Contains(extra.Name) && !HandWrittenMembers.Contains($"{generated.Name}.{extra.Name}"))
                    drift.Add($"{generated.Name}.{extra.Name} is in the generated class but not in the schema ({path})");
            }
        }

        private static PropertyInfo? FindMember(Type generated, string schemaName, HashSet<string> expected)
        {
            string memberName = RenamedGeneratedMembers.TryGetValue($"{generated.Name}.{schemaName}", out string? renamed) ? renamed : schemaName;
            expected.Add(memberName);
            return generated.GetProperty(memberName, BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly);
        }

        /// <summary>
        /// Writes a value through the generated property and checks the attribute that appears on the element is
        /// the schema's: a property can exist and still read a differently named attribute.
        /// </summary>
        private static bool AttributeBindsToName(Type generated, PropertyInfo property, string attributeName)
        {
            if (!property.CanWrite)
                return false;

            object? sample = property.PropertyType switch
            {
                Type t when t == typeof(string) => "x",
                Type t when t == typeof(decimal) => 1m,
                Type t when t == typeof(int) => 1,
                Type t when t == typeof(bool) => true,
                Type t when Nullable.GetUnderlyingType(t) == typeof(int) => 1,
                Type t when Nullable.GetUnderlyingType(t) == typeof(bool) => true,
                _ => null,
            };
            if (sample == null)
                return false;

            object instance = Activator.CreateInstance(generated)!;
            property.SetValue(instance, sample);
            return ((Xml.Schema.Linq.XTypedElement)instance).Untyped.Attribute(XName.Get(attributeName, "")) != null;
        }

        private static IEnumerable<XmlSchemaElement> ChildElements(XmlSchemaParticle? particle)
        {
            switch (particle)
            {
                case XmlSchemaElement element:
                    yield return element;
                    break;
                case XmlSchemaGroupBase group:
                    foreach (XmlSchemaElement child in group.Items.Cast<XmlSchemaParticle>().SelectMany(ChildElements).GroupBy(e => e.QualifiedName).Select(g => g.First()))
                        yield return child;
                    break;
            }
        }

        private static void CheckEnumeration(XmlSchemaSimpleType simple, List<string> drift)
        {
            string[] values = (simple.Content as XmlSchemaSimpleTypeRestriction)?.Facets.OfType<XmlSchemaEnumerationFacet>().Select(f => f.Value ?? "").ToArray() ?? [];
            if (values.Length == 0)
                return;

            string typeName = simple.QualifiedName.Name;
            if (!EnumerationConsumers.TryGetValue(typeName, out Func<string, object>? consume))
            {
                drift.Add($"enumeration {typeName} has no registered consumer (add one to {nameof(EnumerationConsumers)})");
                return;
            }

            object fallback = consume("\u0001not a schema value");
            Dictionary<object, string> seen = new();
            foreach (string value in values)
            {
                object result = consume(value);
                if (seen.TryGetValue(result, out string? other))
                    drift.Add($"enumeration {typeName}: '{value}' and '{other}' both become {result}");
                else
                    seen[result] = value;

                if (result.Equals(fallback) && !EnumerationValuesEqualToFallback.Contains($"{typeName}.{value}"))
                    drift.Add($"enumeration {typeName}: '{value}' is not recognised by its consumer and becomes the fallback {result}");
            }
        }

        private static List<string> ValidateAgainstSchema(XmlSchemaSet schemas, string xmlText)
        {
            List<string> problems = new();
            XmlReaderSettings settings = new() { ValidationType = ValidationType.Schema, Schemas = schemas };
            settings.ValidationEventHandler += (_, e) => problems.Add($"line {e.Exception?.LineNumber}: {e.Message}");
            using XmlReader reader = XmlReader.Create(new StringReader(xmlText), settings);
            while (reader.Read())
            {
            }

            return problems;
        }

        private static string Join(IEnumerable<string> lines) => string.Join(Environment.NewLine, lines);

        [TestMethod]
        public void ShippedSchemaMatchesGeneratedClass()
        {
            List<string> drift = FindDrift(CompileSchema(ReadShippedSchemaText()));
            Assert.AreEqual(0, drift.Count, "Schema and webannotationusersettings.cs drifted; regenerate the class from the schema:" + Environment.NewLine + Join(drift));
        }

        [TestMethod]
        public void ShippedUserSettingsValidatesAgainstSchema()
        {
            List<string> problems = ValidateAgainstSchema(CompileSchema(ReadShippedSchemaText()), File.ReadAllText(FindWebAnnotationFile("UserSettings.xml")));
            Assert.AreEqual(0, problems.Count, "UserSettings.xml does not follow WebAnnotationUserSettings.xsd:" + Environment.NewLine + Join(problems));
        }

        [TestMethod]
        public void ShippedSchemaDeclaresTheElementsTheLoaderReliesOn()
        {
            string[] globalElements = CompileSchema(ReadShippedSchemaText()).GlobalElements.Values.Cast<XmlSchemaElement>().Select(e => e.QualifiedName.Name).ToArray();
            CollectionAssert.IsSubsetOf(new[] { "UserSettings", "Hotkey", "Action", "Parameters", "CreateStructureCommandAction" }, globalElements);
        }

        [TestMethod]
        public void RenamedAttributeInSchemaIsReportedAsMissingFromGeneratedClass()
        {
            string mutated = ReadShippedSchemaText().Replace("<xs:attribute name=\"KeyName\"", "<xs:attribute name=\"KeyLabel\"");
            Assert.AreNotEqual(ReadShippedSchemaText(), mutated, "mutation did not apply");

            List<string> drift = FindDrift(CompileSchema(mutated));
            Assert.IsTrue(drift.Any(d => d.Contains("Hotkey/@KeyLabel has no property")), Join(drift));
            Assert.IsTrue(drift.Any(d => d.Contains("Hotkey.KeyName is in the generated class but not in the schema")), Join(drift));
        }

        [TestMethod]
        public void AttributeAddedToSchemaIsReportedAsMissingFromGeneratedClass()
        {
            string mutated = ReadShippedSchemaText().Replace(
                "<xs:attribute name=\"Alt\" type=\"xs:boolean\" default=\"0\" use=\"optional\"/>",
                "<xs:attribute name=\"Alt\" type=\"xs:boolean\" default=\"0\" use=\"optional\"/><xs:attribute name=\"Meta\" type=\"xs:boolean\" use=\"optional\"/>");
            Assert.AreNotEqual(ReadShippedSchemaText(), mutated, "mutation did not apply");

            List<string> drift = FindDrift(CompileSchema(mutated));
            CollectionAssert.AreEqual(new[] { "Hotkey/@Meta has no property on Hotkey" }, drift);
        }

        [TestMethod]
        public void AttributeRemovedFromSchemaIsReportedAsStaleInGeneratedClass()
        {
            string mutated = ReadShippedSchemaText().Replace("<xs:attribute name=\"Alt\" type=\"xs:boolean\" default=\"0\" use=\"optional\"/>", "");
            Assert.AreNotEqual(ReadShippedSchemaText(), mutated, "mutation did not apply");

            List<string> drift = FindDrift(CompileSchema(mutated));
            CollectionAssert.AreEqual(new[] { "Hotkey.Alt is in the generated class but not in the schema (Hotkey)" }, drift);
        }

        [TestMethod]
        public void ElementAddedToSchemaIsReportedAsMissingGeneratedClass()
        {
            string mutated = ReadShippedSchemaText().Replace(
                "<xs:element name=\"ToggleLocationTerminalCommandAction\">",
                "<xs:element name=\"ToggleLocationFlagCommandAction\"><xs:complexType/></xs:element><xs:element name=\"ToggleLocationTerminalCommandAction\">");
            Assert.AreNotEqual(ReadShippedSchemaText(), mutated, "mutation did not apply");

            CollectionAssert.AreEqual(new[] { "element <ToggleLocationFlagCommandAction> has no generated class" }, FindDrift(CompileSchema(mutated)));
        }

        [TestMethod]
        public void ChildElementAddedToSchemaIsReportedAsMissingFromGeneratedClass()
        {
            string mutated = ReadShippedSchemaText().Replace(
                "<xs:element ref=\"Variable\"/>",
                "<xs:element ref=\"Variable\"/><xs:element ref=\"Hotkey\"/>");
            Assert.AreNotEqual(ReadShippedSchemaText(), mutated, "mutation did not apply");

            List<string> drift = FindDrift(CompileSchema(mutated));
            CollectionAssert.AreEqual(new[] { "Parameters/Hotkey has no property on Parameters" }, drift);
        }

        [TestMethod]
        public void EnumerationValueAddedToSchemaIsReportedAsUnknownToItsConsumer()
        {
            string mutated = ReadShippedSchemaText().Replace(
                "<xs:enumeration value=\"Ellipse\"/>",
                "<xs:enumeration value=\"Ellipse\"/><xs:enumeration value=\"Spline\"/>");
            Assert.AreNotEqual(ReadShippedSchemaText(), mutated, "mutation did not apply");

            List<string> drift = FindDrift(CompileSchema(mutated));
            Assert.IsTrue(drift.Any(d => d.Contains("'Spline' is not recognised by its consumer")), Join(drift));
        }

        [TestMethod]
        public void NewEnumerationTypeWithoutConsumerIsReported()
        {
            string mutated = ReadShippedSchemaText().Replace(
                "<xs:simpleType name=\"AnnotationType\">",
                "<xs:simpleType name=\"Colour\"><xs:restriction base=\"xs:string\"><xs:enumeration value=\"Red\"/></xs:restriction></xs:simpleType><xs:simpleType name=\"AnnotationType\">");
            Assert.AreNotEqual(ReadShippedSchemaText(), mutated, "mutation did not apply");

            List<string> drift = FindDrift(CompileSchema(mutated));
            Assert.AreEqual(1, drift.Count, Join(drift));
            StringAssert.Contains(drift[0], "enumeration Colour has no registered consumer");
        }

        [TestMethod]
        public void UserSettingsAttributeTheSchemaDoesNotDeclareIsRejectedByValidation()
        {
            string xml = File.ReadAllText(FindWebAnnotationFile("UserSettings.xml"));
            string mutated = xml.Replace("<Hotkey KeyName=\"C\" Action=\"Annotate Cell with Circle\"/>", "<Hotkey KeyName=\"C\" Action=\"Annotate Cell with Circle\" Meta=\"1\"/>");
            Assert.AreNotEqual(xml, mutated, "mutation did not apply");

            List<string> problems = ValidateAgainstSchema(CompileSchema(ReadShippedSchemaText()), mutated);
            Assert.AreEqual(1, problems.Count, Join(problems));
            StringAssert.Contains(problems[0], "Meta");
        }

        [TestMethod]
        public void UserSettingsAnnotationTypeOutsideTheEnumerationIsRejectedByValidation()
        {
            string xml = File.ReadAllText(FindWebAnnotationFile("UserSettings.xml"));
            string mutated = xml.Replace("AnnotationType=\"Circle\"", "AnnotationType=\"Sphere\"");
            Assert.AreNotEqual(xml, mutated, "mutation did not apply");

            Assert.IsTrue(ValidateAgainstSchema(CompileSchema(ReadShippedSchemaText()), mutated).Count > 0);
        }
    }
