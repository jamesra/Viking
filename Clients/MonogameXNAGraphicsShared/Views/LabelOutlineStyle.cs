namespace VikingXNAGraphics
{
    /// <summary>How the text of an outlined <see cref="LabelView"/> is drawn.</summary>
    public enum LabelOutlineStyle
    {
        /// <summary>No outline; the text is drawn as it is.</summary>
        Off,

        /// <summary>Black text with a thin white outline.</summary>
        BlackTextWhiteOutline,

        /// <summary>White text with a thin black outline.</summary>
        WhiteTextBlackOutline,
    }
}
